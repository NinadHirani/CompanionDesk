#!/usr/bin/env node
'use strict';

// Builds the pure-logic part of the web/mobile bundle: wraps the small, pure
// src modules into dual-mode files under web/core/. In Node (tests, Electron)
// they keep working via require(); in a browser <script> each one defines a
// root global the web bridge and the renderer read. The module bodies are
// copied verbatim; only the loader around them changes. Modules with
// filesystem or Electron dependencies are deliberately NOT wrapped here: they
// are desktop-only and the bridge answers those channels with desktop_only.

const fs = require('fs');
const path = require('path');

const MODULES = [
  { src: 'src/dates.js', global: 'CompanionDates', requires: {} },
  { src: 'src/settings.js', global: 'CompanionSettings', requires: {} },
  { src: 'src/skills.js', global: 'CompanionSkills', requires: {} },
  { src: 'src/patterns.js', global: 'CompanionPatterns', requires: {} },
  { src: 'src/grades.js', global: 'CompanionGrades', requires: {} },
  { src: 'src/gradebook.js', global: 'CompanionGradebook', requires: { './grades': 'CompanionGrades' } },
  { src: 'src/brief.js', global: 'CompanionBrief', requires: { './extraction-core': 'CompanionCore' } },
  { src: 'src/services.js', global: 'CompanionServices', requires: { './brief': 'CompanionBrief', './settings': 'CompanionSettings', './extraction-core': 'CompanionCore' } },
  { src: 'src/ics.js', global: 'CompanionIcs', requires: {} },
  { src: 'src/calendar.js', global: 'CompanionCalendar', requires: { './ics': 'CompanionIcs', './settings': 'CompanionSettings', './dates': 'CompanionDates', path: '__WEB_PATH_SHIM__' } },
];

// calendar.js only ever calls path.basename(); a two-line shim covers it.
const PATH_SHIM = "const __WEB_PATH_SHIM__ = { basename: (p) => String(p).split(/[\\\\/]/).pop() };";

const root = path.join(__dirname, '..');
for (const m of MODULES) {
  let body = fs.readFileSync(path.join(root, m.src), 'utf8');
  body = body.replace(/^'use strict';\n/, '').replace(/\s+$/, '\n');
  const map = {};
  for (const [k, v] of Object.entries(m.requires)) map[k] = v;
  const out = [
    '// GENERATED by scripts/web-wrap.js from ' + m.src + ' for the web/mobile bundle.',
    '// Edit src/' + path.basename(m.src) + ' and rerun scripts/build-web.sh; do not edit this copy.',
    "(function (root) {",
    "  'use strict';",
    "  const module = { exports: {} };",
    PATH_SHIM,
    "  const require = (p) => {",
    "    const g = " + JSON.stringify(map) + ";",
    "    if (!(p in g)) throw new Error('web bundle: unhandled require \"' + p + '\"');",
    "    return root[g[p]];",
    "  };",
    body,
    "  root." + m.global + " = module.exports;",
    "})(typeof self !== 'undefined' ? self : this);",
    "",
  ].join('\n');
  fs.writeFileSync(path.join(root, 'web/core', path.basename(m.src)), out);
}
console.log('web/core wrapped: ' + MODULES.length + ' modules');
